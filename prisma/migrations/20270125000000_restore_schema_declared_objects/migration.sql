-- P0 schema drift repair: create the objects prisma/schema.prisma has declared
-- since April that no migration ever created.
--
-- WHY: the production database is missing User.archived_at (and the objects
-- below). Every Prisma read of User selects every scalar column, so every User
-- read, the signup path and every cron tick fails with
-- "column User.archived_at does not exist". The same is true for UserProfile,
-- NotificationPreferences and the four tables. The fields were added to
-- schema.prisma without a migration (for example 69c80ee1, #35), and CI's
-- schema-parity diff was informational, so nothing failed.
--
-- WHAT (exactly what schema.prisma declares; DDL generated by
-- `prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma
-- --script` with Prisma 6.19.3, then wrapped in existence guards):
--   enum   ListType (grocery, shopping)
--   column User.archived_at
--   column UserProfile.bio, weight_unit, meals_per_day, water_goal_oz,
--          calorie_display, onboardingCompleted
--   column NotificationPreferences.daily_checkin_enabled,
--          weekly_summary_enabled, new_client_alerts
--   table  UserPreferences, Recipe, SavedRecipe, ListItem, with their primary
--          keys, unique constraints, indexes and foreign keys (ON DELETE
--          RESTRICT ON UPDATE CASCADE: the Prisma default for a required
--          relation with no declared onDelete).
--
-- SAFETY:
--   * Additive only. No DROP, no data rewrite, no backfill. ADD COLUMN with a
--     constant default is a catalog-only change on PostgreSQL 11+ (existing
--     rows read the default; the table is not rewritten).
--   * Idempotent: every statement is guarded (IF NOT EXISTS, catalog checks,
--     DROP POLICY IF EXISTS before CREATE POLICY), so a re-run is a no-op.
--   * Not silently wrong: a guard skips an object that already exists, so the
--     final block asserts the shape of every object (type, typmod, nullability,
--     default present, constraint actions, RLS flags) and raises if anything
--     differs, which rolls the whole file back.
--   * One transaction with bounded lock waits: lock_timeout 5 s, statement
--     timeout 30 s (SET LOCAL, so nothing leaks into later migrations). On a
--     timeout the file rolls back as a whole; recover with
--     `prisma migrate resolve --rolled-back 20270125000000_restore_schema_declared_objects`
--     and re-deploy.
--
-- RLS (the four new tables): the S1-DB-01 server-only posture used for the
-- existing per-user tables UserAIQuota and NudgeLog
-- (20261224000000_rls_close_public_exposure): ENABLE + FORCE RLS, PERMISSIVE
-- FOR ALL TO service_role, RESTRICTIVE deny-all TO anon and TO authenticated,
-- API-role privileges revoked. The tables are reached only through the backend
-- Prisma client; the mobile app issues no PostgREST (.from) calls.
--
-- ROLLBACK: forward-fix only. Every application release since April already
-- expects these objects, so rolling the app back never needs the schema rolled
-- back. down.sql exists for the CI reversibility proof; running it in
-- production would bring the outage back and delete any rows written since.

BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

-- Entry gate: the API roles the RLS section references must exist
-- (Supabase provides them; CI applies prisma/migrations/_supabase_bootstrap.sql).
DO $gate$
BEGIN
  IF (SELECT count(*) FROM pg_catalog.pg_roles
       WHERE rolname IN ('anon', 'authenticated', 'service_role')) <> 3 THEN
    RAISE EXCEPTION 'restore_schema_declared_objects: Supabase API roles (anon, authenticated, service_role) are missing';
  END IF;
END
$gate$;

