    SELECT 1 FROM pg_catalog.pg_type t
      JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
     WHERE t.typname = 'ListType' AND n.nspname = current_schema()
  ) THEN
    CREATE TYPE "ListType" AS ENUM ('grocery', 'shopping');
  END IF;
END
