/**
 * community-voice.repository.ts — data access for v3-3 community voice notes.
 *
 * Tenant scoping follows the v1-2 / v3-1 doctrine: the app connects as the
 * Supabase service_role (BYPASSRLS), so isolation is enforced HERE in explicit
 * WHERE clauses (and again at the DB by the migration's RLS policies as
 * defence-in-depth). Every read is cursor-paginated with a clamped `take` so an
 * internal caller can never trigger an unbounded scan (Failure #28).
 */

export interface Page<T> {
  items: T[];
  nextCursor: string | null;
}

const PAGE_DEFAULT_LIMIT = 20;
const PAGE_MAX_LIMIT = 50;

function clampLimit(limit: number | undefined): number {
  const n = limit ?? PAGE_DEFAULT_LIMIT;
  if (!Number.isFinite(n)) return PAGE_DEFAULT_LIMIT;
  return Math.max(1, Math.min(PAGE_MAX_LIMIT, Math.trunc(n)));
}

/** Fields needed to durably insert a voice note after upload confirmation. */
export interface VoiceNoteSeed {
  workspaceId: string;
  cohortId: string | null;
  conversationId: string | null;
  authorId: string;
  storageKey: string;
  durationMs: number;
  bytes: number;
  mimeType: string;
  // Sourced from Prisma's own generated Bytes input type so the seed stays in
  // lock-step with the column type across SDK bumps (no hand-written
  // Uint8Array generic to drift, no cast). VOICE-BE: the phone's bars, one
  // byte each (peaksToBytes), or null when it sent none.
  waveformPeaks: Prisma.CommunityVoiceNoteUncheckedCreateInput['waveform_peaks'];
  /** VOICE-BE: the thread's first chat message this note replies to. */
  parent: { id: string; at: Date } | null;
  /** A coach's note answers the space's open client messages (as a coach's text does). */
  answersClients: boolean;
}

/** What a voice note view adds per viewer (VOICE-BE): names, coach, heard, chat link. */
export interface VoiceViewExtras {
  coachId: string | null;
  names: Map<string, string | null>;
  fullName: (space: string | null, person: string) => boolean;
  heardAt: Map<string, Date>;
  chat: Map<string, { parent_message_id: string | null }>;
}

/**
 * VOICE-IDEM-BE: a note's id is fixed by its storage key (a v4-shaped UUID
 * from SHA-256), so the table's primary key lets one row exist per recording
 * even when two creates race (the schema has no unique index on the key).
 */
export function voiceNoteIdFor(storageKey: string): string {
  const h = createHash('sha256').update(`community.voice_note.v1|${storageKey}`).digest();
  h[6] = (h[6] & 0x0f) | 0x40;
  h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString('hex');
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

/** Hide a space voice note's chat message with the note (author delete, moderation). */
export async function hideVoiceChatMessage(tx: Prisma.TransactionClient, voiceNoteId: string, at: Date): Promise<void> {
  await tx.communityMessage.updateMany({
    where: { id: voiceNoteId, kind: 'voice', deleted_at: null },
    data: { deleted_at: at, visibility: 'hidden' },
  });
}

export interface VoiceListFilter {
  workspaceId: string;
  cohortId: string | null;
  conversationId: string | null;
  /** Cohort ids the caller may see (student path); empty = none. */
  visibleCohortIds?: string[];
  /** When true, the caller is a coach/owner and sees the whole workspace. */
  isCoach: boolean;
  /** The caller's user id — used to scope DM-thread visibility on the student path. */
  viewerId: string;
  limit?: number;
  cursor?: string;
}

@Injectable()
export class CommunityVoiceRepository {
  constructor(private readonly prisma: PrismaService) {}

  /**
   * Insert a voice note in one transaction. VOICE-BE: a space note also gets
   * its chat message (kind 'voice', sharing the note's id and time), so the
   * space chat, its new-messages line, threads and reports see one item; a
   * coach's note answers the space's open client messages. VOICE-IDEM-BE:
   * when a racing create already wrote this key's row, nothing is written and
   * that row comes back with `replayed` (the service decides 201 or 409).
   */
  async createVoiceNote(seed: VoiceNoteSeed): Promise<{ row: CommunityVoiceNote; replayed: boolean }> {
    try {
      return { row: await this.insertVoiceNote(seed), replayed: false };
    } catch (err) {
      const first = err instanceof Prisma.PrismaClientKnownRequestError && err.code === 'P2002'
        ? await this.findByStorageKey(seed.storageKey)
        : null;
      if (!first) throw err;
      return { row: first, replayed: true };
    }
  }

  private async insertVoiceNote(seed: VoiceNoteSeed): Promise<CommunityVoiceNote> {
    // FR-1174: a coach's space note answers only the open client messages the coach can read.
    const open = seed.answersClients && seed.cohortId
      ? await openClientMessagesReadBy(this.prisma, seed.cohortId, seed.authorId) : null;
    return this.prisma.$transaction(async (tx) => {
      const created = await tx.communityVoiceNote.create({
        data: {
          id: voiceNoteIdFor(seed.storageKey),
          workspace_id: seed.workspaceId,
          cohort_id: seed.cohortId,
          conversation_id: seed.conversationId,
          author_id: seed.authorId,
          storage_key: seed.storageKey,
          duration_ms: seed.durationMs,
          bytes: BigInt(seed.bytes),
          mime_type: seed.mimeType,
          waveform_peaks: seed.waveformPeaks ?? null,
        },
      });
      if (created.cohort_id) {
        await tx.communityMessage.create({
          data: {
            id: created.id,
            created_at: created.created_at,
            workspace_id: created.workspace_id,
            cohort_id: created.cohort_id,
            scope: 'cohort',
            kind: 'voice',
            sender_id: created.author_id,
            voice_duration_ms: created.duration_ms,
            voice_mime_type: created.mime_type,
            voice_size_bytes: seed.bytes,
            parent_message_id: seed.parent?.id ?? null,
            parent_message_at: seed.parent?.at ?? null,
          },
        });
        if (open) {
          await tx.communityMessage.updateMany({
            where: open,
            data: { coach_replied_at: created.created_at },
          });
        }
      }
      return created;
    });
  }

  /** A chat message a voice note may reply to (any scope; the service checks it). */
  async findChatMessage(id: string) {
    return this.prisma.communityMessage.findFirst({ where: { id } });
  }

  /** VOICE-BE: everything a page of voice note views needs for one viewer, in four reads. */
  async viewExtras(viewerId: string, rows: CommunityVoiceNote[]): Promise<VoiceViewExtras> {
    const ids = rows.map((r) => r.id);
    const workspaceId = rows[0]?.workspace_id ?? null;
    const [workspace, users, heard, chat, fullName] = await Promise.all([
      workspaceId
        ? this.prisma.communityWorkspace.findUnique({ where: { id: workspaceId }, select: { coach_id: true } })
        : null,
      this.prisma.user.findMany({ where: { id: { in: [...new Set(rows.map((r) => r.author_id))] } }, select: { id: true, name: true } }),
      this.prisma.communityVoiceNoteListen.findMany({ where: { user_id: viewerId, voice_note_id: { in: ids } } }),
      this.prisma.communityMessage.findMany({
        where: { id: { in: ids }, kind: 'voice' },
        select: { id: true, parent_message_id: true },
      }),
      fullNamesFor(this.prisma, viewerId, workspaceId, rows.map((r) => [r.cohort_id, r.author_id] as const)),
    ]);
    return {
      coachId: workspace?.coach_id ?? null,
      names: new Map(users.map((u) => [u.id, u.name])),
      fullName,
      heardAt: new Map(heard.map((h) => [h.voice_note_id, h.heard_at])),
      chat: new Map(chat.map((m) => [m.id, { parent_message_id: m.parent_message_id }])),
    };
  }

  /** VOICE-BE heard marker: the first time this listener heard the note (idempotent). */
  async markHeard(voiceNoteId: string, userId: string): Promise<Date> {
    const row = await this.prisma.communityVoiceNoteListen.upsert({
      where: { voice_note_id_user_id: { voice_note_id: voiceNoteId, user_id: userId } },
      create: { voice_note_id: voiceNoteId, user_id: userId },
      update: {},
    });
    return row.heard_at;
  }

  /** VOICE-BE consent: when this person first saw the voice consent card, or null. */
  async consentSeenAt(userId: string): Promise<Date | null> {
    const row = await this.prisma.communityVoiceConsent.findUnique({ where: { user_id: userId } });
    return row?.seen_at ?? null;
  }

  async markConsentSeen(userId: string): Promise<Date> {
    const row = await this.prisma.communityVoiceConsent.upsert({
      where: { user_id: userId },
      create: { user_id: userId },
      update: {},
    });
    return row.seen_at;
  }

  /** Any row (live or soft-deleted) already holding this storage key. */
  async findByStorageKey(storageKey: string): Promise<CommunityVoiceNote | null> {
    return this.prisma.communityVoiceNote.findFirst({ where: { storage_key: storageKey } });
  }

  /** Every note an author recorded (live or soft-deleted), for account deletion. */
  async findAllByAuthor(authorId: string): Promise<Array<{ id: string; storage_key: string }>> {
    return this.prisma.communityVoiceNote.findMany({
      where: { author_id: authorId },
      select: { id: true, storage_key: true },
    });
  }

  async findById(id: string): Promise<CommunityVoiceNote | null> {
    return this.prisma.communityVoiceNote.findUnique({ where: { id } });
  }

  /**
   * B-610-5 round 5: durably record the recording erasure BEFORE the row is
   * soft-deleted or storage is called (see voice-erasure.ts).
   */
  async recordErasure(storageKeys: string[], reason: VoiceErasureReason): Promise<VoiceErasureRow[]> {
    return recordVoiceErasures(this.prisma, objectTargets(storageKeys), reason);
  }

  /**
   * C-610-10 (author-delete half): record the recording erasure AND soft-delete
   * the note and its search row in ONE transaction, then return the work so
   * the caller can try storage after the commit. VOICE-BE: a space note's
   * chat message is hidden in the same transaction.
   *
   * Before this, the erasure row committed first and the soft delete second:
   * a crash (or a failed write) between them left a LIVE note whose recording
   * the retry cron would then erase, so it stopped playing. Now either all
   * three writes commit, or none do and the member's delete fails visibly
   * with nothing changed. Storage is never called inside the transaction.
   * Idempotent: a note that is already soft-deleted keeps its first
   * soft_deleted_at.
   */
  async softDeleteWithErasure(
    note: Pick<CommunityVoiceNote, 'id' | 'storage_key'>,
    reason: VoiceErasureReason,
    at: Date = new Date(),
  ): Promise<VoiceErasureRow[]> {
    return this.prisma.$transaction(async (tx) => {
      const work = await recordVoiceErasures(tx, objectTargets([note.storage_key]), reason, at);
      await tx.communityVoiceNote.updateMany({
        where: { id: note.id, soft_deleted_at: null },
        data: { soft_deleted_at: at },
      });
      await tx.communitySearchEntry.updateMany({
        where: { kind: 'voice_note_transcript', targetId: note.id, softDeletedAt: null },
        data: { softDeletedAt: at },
      });
      await hideVoiceChatMessage(tx, note.id, at);
      return work;
    });
  }

  /** Try the recorded erasure now; an unverified row stays open for the retry cron. */
  async attemptErasure(
    storage: VoiceErasureStorage,
    rows: VoiceErasureRow[],
  ): Promise<VoiceErasureOutcome> {
    return attemptVoiceErasures(this.prisma, storage, rows);
  }

  /**
   * List voice notes most-recent-first. A coach/owner sees every non-deleted
   * note in the workspace (optionally narrowed to a cohort/conversation); a
   * student sees notes that are NOT soft-deleted AND either:
   *   - a channel/cohort note in a cohort they can access (or the workspace
   *     hall when cohort_id is null), or
   *   - a DM note they authored (DM participant resolution is enforced by the
   *     service before this query runs).
   * Cursor pagination fetches limit+1 rows to detect the next page.
   */
  async list(filter: VoiceListFilter): Promise<Page<CommunityVoiceNote>> {
    const take = clampLimit(filter.limit);

    const visibility: Prisma.CommunityVoiceNoteWhereInput = filter.isCoach
      ? {}
      : {
          OR: [
            // Channel/cohort notes visible to this member.
            {
              conversation_id: null,
              OR: [
                { cohort_id: null },
                {
                  cohort_id: {
                    in:
                      filter.visibleCohortIds && filter.visibleCohortIds.length > 0
                        ? filter.visibleCohortIds
                        : ['__none__'],
                  },
                },
              ],
            },
            // DM notes the caller authored (further participant scoping is in
            // the service layer, which knows the conversation roster).
            { conversation_id: { not: null }, author_id: filter.viewerId },
          ],
        };

    const where: Prisma.CommunityVoiceNoteWhereInput = {
      workspace_id: filter.workspaceId,
      soft_deleted_at: null,
      ...(filter.cohortId !== null ? { cohort_id: filter.cohortId } : {}),
      ...(filter.conversationId !== null ? { conversation_id: filter.conversationId } : {}),
      ...visibility,
    };

    const rows = await this.prisma.communityVoiceNote.findMany({
      where,
      orderBy: [{ created_at: 'desc' }, { id: 'desc' }],
      take: take + 1,
      ...(filter.cursor ? { cursor: { id: filter.cursor }, skip: 1 } : {}),
    });

    const items = rows.slice(0, take);
    const nextCursor = rows.length > take ? items[items.length - 1].id : null;
    return { items, nextCursor };
  }
}
