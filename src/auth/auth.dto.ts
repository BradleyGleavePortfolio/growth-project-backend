export class SelectRoleDto {
  // Coach elevation via client input is disabled (see auth.service.selectRole).
  // We still accept the field to keep the API contract stable, but only `student`
  // is honored — a `coach` value will be rejected server-side with 403.
  @ApiProperty({ enum: ['coach', 'student'], example: 'student' })
  @IsIn(['coach', 'student'])
  role!: 'coach' | 'student';

  // Legacy: previously a fake/unused `coach_code`. Still accepted for API
  // back-compat. If supplied (and `invite_code` is not) it is treated as an
  // invite code and validated the same way — so old clients that somehow send
  // this field aren't silently broken.
  @ApiPropertyOptional({
    deprecated: true,
    description: 'Legacy alias of invite_code; prefer invite_code on new clients.',
    maxLength: 32,
  })
  @IsOptional()
  @IsString()
  @MaxLength(32)
  coach_code?: string;

  // Real invite code (e.g. GP-A1B2C3) generated by a coach. Optional — signup
  // still works without one (the user just has no coach until they redeem later).
  @ApiPropertyOptional({ example: 'GP-A1B2C3', maxLength: 32 })
  @IsOptional()
  @IsString()
  @MaxLength(32)
  invite_code?: string;
}

// Public invite-code preview body. Length / format checks are deliberately
