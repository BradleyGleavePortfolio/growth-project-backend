import {
  IsEmail,
  IsIn,
  IsOptional,
  IsString,
  Matches,
  MaxLength,
  MinLength,
} from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

// SECURITY: DTOs for high-risk auth endpoints that touch the User model and/or
// the `role` field. The global ValidationPipe (src/main.ts) is configured with
// `whitelist: true, forbidNonWhitelisted: true`, so any field not listed here
// is stripped/rejected — preventing mass-assignment on role/coach_id.
// See audit C3/C4.

export class RegisterDto {
  @ApiProperty({ example: 'jane@example.com', format: 'email' })
  @IsEmail()
  email!: string;

  @ApiProperty({ minLength: 8, example: 'correct horse battery staple' })
  @IsString()
  @MinLength(8)
  password!: string;

  @ApiProperty({ example: 'Jane Doe' })
  @IsString()
  @MinLength(1)
  name!: string;

  @ApiPropertyOptional({ example: '+15555550100' })
  @IsOptional()
  @IsString()
  phone?: string;

  @ApiPropertyOptional({ description: 'Signup attribution ref (e.g. importer-extension)' })
  @IsOptional()
  @IsString()
  @MaxLength(64)
  @Matches(/^[a-z0-9_-]+$/, {
    message: 'ref must be lowercase alphanumeric with dashes/underscores',
  })
  ref?: string;
}

